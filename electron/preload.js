const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (channel) => (fn) => ipcRenderer.on(channel, (_e, payload) => fn(payload));

contextBridge.exposeInMainWorld('pilot', {
  getInitial: () => ipcRenderer.invoke('get-initial'),
  clipInfoToggle: () => ipcRenderer.invoke('clipinfo-toggle'),
  clipInfoHeight: (h) => ipcRenderer.invoke('clipinfo-height', h),
  onClipInfo: on('clipinfo'),
  stabilize: (action, args = {}) => ipcRenderer.invoke('stabilize', { action, ...args }),
  onStabilize: on('stabilize'),
  premiere: (action, args = {}) => ipcRenderer.invoke('premiere', { action, ...args }),
  onPremiere: on('premiere'),
  libraryBackup: (action, options) => ipcRenderer.invoke('library-backup', action, options),
  onLibraryBackup: on('library-backup'),
  saveSettings: (s) => ipcRenderer.invoke('save-settings', s),
  saveNow: () => ipcRenderer.invoke('save-now'),
  launchResolve: () => ipcRenderer.invoke('launch-resolve'),
  pickFolder: (current) => ipcRenderer.invoke('pick-folder', current),
  pickResolve: () => ipcRenderer.invoke('pick-resolve'),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  openLog: () => ipcRenderer.invoke('open-log'),
  checkPath: (p) => ipcRenderer.invoke('check-path', p),
  isNetworkPath: (p) => ipcRenderer.invoke('is-network-path', p),
  pickFolders: (current) => ipcRenderer.invoke('pick-folders', current),
  scanDays: (dirs) => ipcRenderer.invoke('scan-days', dirs),
  createProject: (args) => ipcRenderer.invoke('create-project', args),
  planSeries: (form) => ipcRenderer.invoke('plan-series', form),
  seriesNames: () => ipcRenderer.invoke('series-names'),
  importSeriesNames: () => ipcRenderer.invoke('import-series-names'),
  createSeries: (form) => ipcRenderer.invoke('create-series', form),
  listSeries: () => ipcRenderer.invoke('list-series'),
  planRename: (args) => ipcRenderer.invoke('plan-rename', args),
  renameSeries: (args) => ipcRenderer.invoke('rename-series', args),
  hasSecrets: () => ipcRenderer.invoke('has-secrets'),
  setSecret: (kind, value) => ipcRenderer.invoke('set-secret', { kind, value }),
  findChats: (kind) => ipcRenderer.invoke('find-chats', kind),
  sendTest: (only) => ipcRenderer.invoke('send-test', only),
  sceneAdd: (names) => ipcRenderer.invoke('scene-add', names),
  sceneRemove: (i) => ipcRenderer.invoke('scene-remove', i),
  sceneClear: () => ipcRenderer.invoke('scene-clear'),
  sceneStart: () => ipcRenderer.invoke('scene-start'),
  sceneStop: () => ipcRenderer.invoke('scene-stop'),
  shutdownCancel: () => ipcRenderer.invoke('shutdown-cancel'),
  renderPresets: () => ipcRenderer.invoke('render-presets'),
  shutdownNow: () => ipcRenderer.invoke('shutdown-now'),
  encoder: (action, args) => ipcRenderer.invoke('encoder', { action, args }),
  night: (action, args) => ipcRenderer.invoke('night', { action, args }),
  handbrake: (action, args) => ipcRenderer.invoke('handbrake', { action, args }),
  quietLift: (action, args) => ipcRenderer.invoke('quietlift', { action, args }),
  feedback: (action, args) => ipcRenderer.invoke('feedback', { action, args }),
  projectAudio: () => ipcRenderer.invoke('project-audio'),
  encPreview: (action, file) => ipcRenderer.invoke('enc-preview', { action, file }),
  pickFiles: (current) => ipcRenderer.invoke('pick-files', current),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  // dropped files -> real paths (File.path no longer exists in Electron 32+)
  pathForFile: (file) => webUtils.getPathForFile(file),
  update: (action) => ipcRenderer.invoke('update', { action }),
  onUpdate: on('update'),
  onEncoder: on('encoder'),
  onScene: on('scene'),
  onNight: on('night'),
  onHandbrake: on('handbrake'),
  onQuietLift: on('quietlift'),
  onFeedback: on('feedback'),
  onEncPreview: on('enc-preview'),
  onRenders: on('renders'),
  onShutdown: on('shutdown'),
  onProjectProgress: on('project-progress'),
  onStatus: on('status'),
  onLog: on('log'),
  onAutosave: on('autosave'),
  onSettings: on('settings'),
});
